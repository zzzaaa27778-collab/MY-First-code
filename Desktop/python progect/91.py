# ==========================================================
# الدرس 091: معالجة الأخطاء (Try, Except, Else, Finally)
# ==========================================================

try:
    # 1. التجربة: نطلب أرقاماً وننفذ عملية قسمة
    a = int(input("أدخل الرقم الأول: "))
    b = int(input("أدخل الرقم الثاني: "))
    result = a / b

except ZeroDivisionError:
    # 2. خطأ مخصص: إذا حاول المستخدم القسمة على صفر
    print("خطأ: لا يمكن القسمة على صفر!")

except ValueError:
    # 3. خطأ مخصص: إذا أدخل المستخدم نصوصاً بدل الأرقام
    print("خطأ: يجب إدخال أرقام صحيحة فقط!")

except Exception as e:
    # 4. خطأ عام: لاقتناص أي أخطاء أخرى
    print(f"حدث خطأ غير متوقع: {e}")

else:
    # 5. يُنفذ فقط عند نجاح الكود وعدم وجود أخطاء
    print(f"ممتاز! نتيجة القسمة هي: {result}")

finally:
    # 6. يُنفذ دائماً مهما كانت النتيجة
    print("تم الانتهاء من فحص العملية بالكامل.")